def cmd_archive(execute: bool = False):
    """Archive files based on scan classification."""
    data = _latest_scan()
    if not data:
        print("No scan found. Run 'scan' first.")
        return
    files = data["files"]

    mode = "EXECUTING" if execute else "DRY RUN"
    print(f"\n{'='*50}")
    print(f"  ARCHIVE {mode}")
    print(f"{'='*50}\n")

    moved = 0
    skipped = 0
    errors = 0
    error_details = []

    for f in files:
        cat = f["category"]

        src = DATA_DIR / f["path"]
        if not src.exists():
            continue

        if cat in ("archive", "knowledge", "duplicate"):
            dest = archive_path("0-personal", f["filename"], f["created"])
        elif cat == "failed":
            dest = ARCHIVE_BASE / "failed" / f["filename"]
        elif cat == "review":
            dest = INBOX / "review" / "nightshift" / f["filename"]
        else:
            continue

        if dest.exists():
            skipped += 1
            if not execute:
                print(f"  SKIP (exists): {f['filename']} -> {dest.relative_to(DATA_DIR)}")
            continue

        if execute:
            try:
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(str(src), str(dest))
                src.unlink()
                moved += 1
            except Exception as e:
                print(f"  ERROR: {f['filename']}: {e}")
                # If copy succeeded but unlink failed, dest exists — next run skips
                error_details.append({"filename": f["filename"], "error": str(e)})
                errors += 1
        else:
            print(f"  {cat:10s} {f['filename'][:45]:45s} -> {str(dest.relative_to(DATA_DIR))}")
            moved += 1

    print(f"\n{'='*50}")
    action = "Moved" if execute else "Would move"
    print(f"  {action}: {moved} files")
    print(f"  Skipped (already exists): {skipped}")
    if errors:
        print(f"  Errors: {errors}")
        # Persist errors for operational observability
        if execute:
            err_path = STATE_DIR / "archive_errors.json"
            err_path.write_text(json.dumps({"date": datetime.now().isoformat(), "errors": error_details}, indent=2))
            print(f"  Error details: {err_path}")
    print(f"{'='*50}")


def cmd_index():
    """Generate _manifest.yaml per month + _index.md in archive.
    Uses scan JSON data when available to avoid re-parsing (CTO issue #8)."""
    if not ARCHIVE_BASE.exists():
        print("Archive directory not found. Run 'archive --execute' first.")
        return

    # Try to load scan data for pre-computed metadata
    scan_lookup = {}
    scan_data = _latest_scan()
    if scan_data:
        for f in scan_data["files"]:
            scan_lookup[f["filename"]] = f
    else:
        print("  No scan data found, will parse files directly.")

    all_entries = []

    for month_dir in sorted(ARCHIVE_BASE.iterdir()):
        if not month_dir.is_dir() or month_dir.name.startswith("_"):
            continue

        entries = []
        for f in sorted(month_dir.glob("*.md")):
            if f.name.startswith("_"):
                continue

            # Use scan data if available, otherwise parse
            if f.name in scan_lookup:
                sd = scan_lookup[f.name]
                entry = {
                    "filename": f.name,
                    "title": sd.get("title", f.stem),
                    "score": sd.get("score"),
                    "domain": sd.get("domain", "personal"),
                    "file_type": sd.get("file_type", "deliverable"),
                    "keywords": sd.get("keywords", []),
                }
            else:
                text = f.read_text(errors="replace")
                meta = parse_metadata_from_text(text, f)
                entry = {
                    "filename": f.name,
                    "title": meta.get("title", f.stem),
                    "score": meta.get("score"),
                    "domain": detect_domain(meta.get("title", ""), text[:1000]),
                    "file_type": classify_file_type(f.name, meta, text),
                    "keywords": extract_keywords(text),
                }

            entries.append(entry)
            all_entries.append({**entry, "month": month_dir.name})

        if entries:
            manifest = {
                "generated": datetime.now().strftime("%Y-%m-%d"),
                "files": entries,
            }
            manifest_path = month_dir / "_manifest.yaml"
            manifest_path.write_text(yaml.dump(manifest, default_flow_style=False, allow_unicode=True))
            print(f"  Manifest: {month_dir.name}/ ({len(entries)} files)")

    # Handle failed/ directory
    failed_dir = ARCHIVE_BASE / "failed"
    if failed_dir.exists():
        for f in sorted(failed_dir.glob("*.md")):
            if f.name.startswith("_"):
                continue
            if f.name in scan_lookup:
                sd = scan_lookup[f.name]
                all_entries.append({
                    "filename": f.name,
                    "title": sd.get("title", f.stem),
                    "score": None,
                    "domain": sd.get("domain", "personal"),
                    "file_type": "failure",
                    "month": "failed",
                })
            else:
                text = f.read_text(errors="replace")
                meta = parse_metadata_from_text(text, f)
                all_entries.append({
                    "filename": f.name,
                    "title": meta.get("title", f.stem),
                    "score": None,
                    "domain": "personal",
                    "file_type": "failure",
                    "month": "failed",
                })

    # Generate _index.md
    lines = []
    lines.append("# Nightshift Archive Index")
    lines.append("")
    lines.append(f"Processed: {datetime.now().strftime('%Y-%m-%d')} | Files: {len(all_entries)}")
    lines.append("")

    months = Counter(e["month"] for e in all_entries)
    lines.append("## By Month")
    lines.append("")
    lines.append("| Month | Files |")
    lines.append("|-------|-------|")
    for month, count in sorted(months.items()):
        lines.append(f"| [{month}]({month}/) | {count} |")
    lines.append("")

    scored = [e for e in all_entries if e.get("score") is not None]
    scored.sort(key=lambda e: e["score"], reverse=True)
    if scored:
        lines.append("## Top 10 Highest-Value Outputs")
        lines.append("")
        lines.append("| File | Score | Domain | Title |")
        lines.append("|------|-------|--------|-------|")
        for e in scored[:10]:
            lines.append(f"| [{e['filename'][:35]}]({e['month']}/{e['filename']}) | {e['score']:.2f} | {e['domain']} | {e['title'][:40]} |")
        lines.append("")

    failed_entries = [e for e in all_entries if e["file_type"] == "failure"]
    if failed_entries:
        lines.append(f"## Failed Tasks ({len(failed_entries)})")
        lines.append("")
        lines.append("| File | Title |")
        lines.append("|------|-------|")
        for e in failed_entries:
            lines.append(f"| [{e['filename'][:40]}](failed/{e['filename']}) | {e['title'][:50]} |")
        lines.append("")

    lines.append("## All Files")
    lines.append("")
    lines.append("| File | Month | Domain | Score | Type | Keywords |")
    lines.append("|------|-------|--------|-------|------|----------|")
    for e in sorted(all_entries, key=lambda x: x.get("filename", "")):
        score_str = f"{e['score']:.2f}" if e.get("score") is not None else "----"
        kw = ", ".join(e.get("keywords", [])[:5])
        lines.append(f"| {e['filename'][:35]} | {e['month']} | {e['domain'][:8]} | {score_str} | {e['file_type'][:10]} | {kw} |")

    index_path = ARCHIVE_BASE / "_index.md"
    index_path.write_text("\n".join(lines))
    print(f"\nIndex saved to: {index_path}")
    print(f"Total archived files indexed: {len(all_entries)}")


