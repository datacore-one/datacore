#!/usr/bin/env python3
"""
Nightshift inbox classifier: scan, report, archive, index.

Discovers all nightshift-related files in 0-personal/0-inbox/ using three-pass
detection, normalizes metadata across formats, classifies files, scores knowledge
candidates, and supports archiving with manifest/index generation.

Run from ~/Data directory.

Subcommands:
    scan     - Discover and classify all nightshift files, output JSON
    report   - Generate human-readable report from latest scan
    archive  - Move files to archive (--execute to actually move, dry-run default)
    index    - Generate _manifest.yaml per month + _index.md in archive
"""

