def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    cmd = sys.argv[1]

    if cmd == "scan":
        cmd_scan()
    elif cmd == "report":
        cmd_report()
    elif cmd == "archive":
        execute = "--execute" in sys.argv
        cmd_archive(execute=execute)
    elif cmd == "index":
        cmd_index()
    else:
        print(f"Unknown command: {cmd}")
        print("Available: scan, report, archive, index")
        sys.exit(1)


if __name__ == "__main__":
    main()
