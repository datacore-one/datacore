#!/usr/bin/env python3
"""One way in (phase F of the tasks and ledger rebuild plan, 2026-10-31).

A space opts in with ONE setting in its `.datacore/config.yaml`:

    ledger:
      org_lists: readonly

It is off by default. With it on:

  * every org list except inbox.org is a generated, read-only projection of
    the ledger: `next_actions.org` is rendered by `ledger_project_org` under a
    GENERATED / READ-ONLY header and left without write bits. (`nightshift.org`
    is already generated by the nightshift module's assignment queue, phase E.)
    A space that still keeps a list the ledger cannot generate (someday.org,
    projects.org, ...) cannot be switched on; `on` names the file.
  * every task change goes through the adapter (`org_workspace_adapter.py`,
    which the GTD MCP tools call) or the app. The adapter writes ledger events
    and regenerates the list; a direct write to the list through the org
    transaction is refused with the adapter command to use.
  * a hand edit (an editor that lifted the read-only bit) is turned into
    adapter commands by `hook`, or refused with the command to use. The edited
    text is saved first, to a file the message names, so nothing is lost.
  * the hourly ingest no longer reads hand edits out of the list.

    org_readonly.py on|off|status --space DIR
    org_readonly.py hook --space DIR [--apply] [--quiet]
    org_readonly.py trial-check --space DIR

`hook` exits 0 when the list holds no hand edit (or every edit was applied),
1 when recognisable edits wait for `--apply`, and 2 when an edit was refused.
`trial-check` ends with one line for a job contract:
`^OK <space> <n> task\\(s\\), 0 lost, 0 doubled` or `FAIL <space> ...`.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import sys
import tempfile
import time
import uuid
from contextlib import contextmanager
from contextvars import ContextVar
from pathlib import Path

LIB = Path(__file__).resolve().parent
sys.path.insert(0, str(LIB))

CONFIG = Path(".datacore") / "config.yaml"
#: Lists the ledger renders and this mode makes read-only.
LISTS = ("next_actions.org",)
#: Generated by another writer already (the nightshift assignment queue, phase E).
GENERATED_ELSEWHERE = ("nightshift.org",)
REFUSED_DIR = Path(".datacore") / "state" / "projection" / "refused"
TRIAL = Path(".datacore") / "state" / "projection" / "readonly-trial.json"
ADAPTER = LIB / "org_workspace_adapter.py"
BLOCK = ("# Phase F trial (one way in): org lists other than inbox.org are generated,\n"
         "# read-only views. Remove these three lines (or run `org_readonly.py off`) to stop.\n"
         "ledger:\n  org_lists: readonly\n")
NOTE = ("# Generated from the ledger. GENERATED, READ-ONLY (one way in, phase F): change a task "
        "with org_workspace_adapter.py or the app. A hand edit is turned into commands by "
        "`org_readonly.py hook --space <space> --apply`, or refused and saved.")

_regenerating: ContextVar[bool] = ContextVar("org_readonly_regenerating", default=False)


class ReadOnlyList(PermissionError):
    """A write to a read-only list that did not come from its projector."""


# -- the setting -------------------------------------------------------------

def enabled(space) -> bool:
    """True iff `space` opted into read-only lists. Unreadable config: off."""
    try:
        import yaml
        data = yaml.safe_load((Path(space) / CONFIG).read_text(encoding="utf-8")) or {}
    except (OSError, ValueError, Exception):  # noqa: BLE001 - a broken file is not an opt-in
        return False
    ledger = data.get("ledger") if isinstance(data, dict) else None
    return isinstance(ledger, dict) and ledger.get("org_lists") == "readonly"


def is_readonly_list(path) -> bool:
    path = Path(path)
    return (path.name in LISTS and path.parent.name == "org"
            and enabled(path.parent.parent))


def adapter_hint(path) -> str:
    return (f"{Path(path).name} is a read-only view of the ledger (one way in). Change tasks with "
            f"`python3 {ADAPTER} update --file {path} --id <ID> --state <STATE>` "
            f"(or add/complete), or through the app; a hand edit is converted by "
            f"`python3 {LIB / 'org_readonly.py'} hook --space {Path(path).parent.parent} --apply`.")


def check_write(path) -> None:
    """Called by the org transaction before every write. Refuses a non-projector write."""
    if not _regenerating.get() and is_readonly_list(path):
        raise ReadOnlyList(adapter_hint(path))


@contextmanager
def regenerating():
    token = _regenerating.set(True)
    try:
        yield
    finally:
        _regenerating.reset(token)


def lock(path) -> None:
    path = Path(path)
    if path.exists() and not path.is_symlink():
        os.chmod(path, 0o444)


def authored_lists(space) -> list[str]:
    """Org lists in `space` the ledger cannot generate (inbox and archives excepted)."""
    org = Path(space) / "org"
    return [p.name for p in sorted(org.glob("*.org"))
            if p.name != "inbox.org" and p.name not in LISTS + GENERATED_ELSEWHERE
            and "archive" not in p.name]


def _write_config(space, text) -> None:
    from file_utils import atomic_write_text
    target = Path(space) / CONFIG
    mode = target.stat().st_mode & 0o777 if target.exists() else 0o644
    atomic_write_text(target, text)
    os.chmod(target, mode)


def switch_on(space) -> tuple[int, str]:
    space = Path(space).resolve()
    from ledger_project_org import phase, project_space
    if phase(space) != 1:
        return 1, f"REFUSED {space.name}: not a Phase 1 space; next_actions.org is not generated here"
    others = authored_lists(space)
    if others:
        return 1, (f"REFUSED {space.name}: these lists are authored text the ledger cannot generate: "
                   f"{', '.join(others)}. Bring them into the ledger (or move them out of org/) first.")
    if enabled(space):
        return 0, f"{space.name}: already read-only"
    cfg = space / CONFIG
    before = cfg.read_text(encoding="utf-8") if cfg.exists() else ""
    if re.search(r"(?m)^ledger:", before):
        return 1, (f"REFUSED {space.name}: {CONFIG} already has a `ledger:` block; add "
                   f"`  org_lists: readonly` under it by hand.")
    _write_config(space, before + ("" if before.endswith("\n") or not before else "\n") + BLOCK)
    line = project_space(space)
    if line.startswith("REFUSED"):
        _write_config(space, before)
        return 1, f"REFUSED {space.name}: the list could not be regenerated, setting left off ({line})"
    _record_trial_start(space)
    return 0, f"{space.name}: org lists are read-only views now ({line})"


def switch_off(space) -> tuple[int, str]:
    space = Path(space).resolve()
    cfg = space / CONFIG
    text = cfg.read_text(encoding="utf-8") if cfg.exists() else ""
    if BLOCK in text:
        text = text.replace(BLOCK, "")
    else:
        text = re.sub(r"(?m)^ledger:\n  org_lists: readonly\n", "", text)
        text = re.sub(r"(?m)^  org_lists: readonly\n", "", text)
    _write_config(space, text)
    from ledger_project_org import project_space, ORG
    line = project_space(space)
    target = space / ORG
    if target.exists():
        os.chmod(target, 0o600)
    return 0, f"{space.name}: read-only lists switched off ({line})"


# -- the adapter's path: events first, then the view -------------------------

def ledger_text(space) -> str:
    """The list exactly as a projection would write it now (the adapter's scratch)."""
    from ledger_project_org import rendered
    return rendered(Path(space), as_of=time.time())


def _this_actor():
    from actor_identity import this_actor
    return this_actor(strict=True)


def _ws_from_text(text):
    from org_workspace import OrgWorkspace
    d = tempfile.mkdtemp(prefix="org-readonly-")
    path = Path(d) / "list.org"
    path.write_text(text, encoding="utf-8")
    ws = OrgWorkspace()
    ws.load(path)
    return ws, path


def _parent_id(node):
    parent = node.parent
    while parent is not None:
        pid = parent.get_property("ID") if hasattr(parent, "get_property") else None
        if pid:
            return pid
        parent = parent.parent
    return None


def commit_text(space, text, *, actor=None, creates=None, dry_run=False) -> dict:
    """Record what `text` (the ledger's list with an adapter edit applied) changes.

    New ids become `item.create`; every other change goes through the same
    three-way diff the Phase 1 path uses (`sync_generated`), given `text`
    rather than the file on disk. Then the list is regenerated from the ledger.
    """
    space = Path(space).resolve()
    actor = actor or _this_actor()
    from ledger.hub import authoritative_state
    from ledger.log import EventLog
    from ledger.genesis import task_payload, valid_time
    from ledger.projection_state import sync_generated
    from ledger_project_org import project_space
    state = authoritative_state(space)
    ws, path = _ws_from_text(text)
    created = []
    for node in ws.all_nodes():
        tid = node.get_property("ID")
        if not tid or tid in state.items:
            continue
        payload = dict((creates or {}).get(tid) or {})
        if not payload:
            created_date, rung = valid_time(node)
            payload = task_payload(node, space.name, created_date, rung)
        payload.update(parent=_parent_id(node), level=None, outline=[])
        if not dry_run:
            EventLog(space, actor).append("item.create", payload)
        created.append(tid)
    if dry_run and created:
        return {"created": len(created), "updated": None, "dismissed": None, "dry_run": True}
    result = sync_generated(space, authoritative_state(space), actor, dry_run, current_text=text)
    result["created"] = len(created)
    if not dry_run:
        result["projection"] = project_space(space)
    return result


# -- the editor hook ---------------------------------------------------------

_STATE_NOISE = re.compile(r"^\s*(- State \"[A-Z]+\"\s+from\s+\"?[A-Z]*\"?.*|CLOSED: \[.*\])\s*$")


def _without_state_noise(org):
    """An org field minus what an editor writes by itself on a state change."""
    org = dict(org or {})
    lines, drawer = [], []
    for line in str(org.get("body") or "").splitlines():
        if line.strip() == ":LOGBOOK:":
            drawer = [line]
            continue
        if drawer:
            drawer.append(line)
            if line.strip() == ":END:":
                kept = [l for l in drawer[1:-1] if not _STATE_NOISE.match(l)]
                if kept:
                    lines.extend([drawer[0], *kept, line])
                drawer = []
            continue
        if not _STATE_NOISE.match(line):
            lines.append(line)
    lines.extend(drawer)
    org["body"] = "\n".join(lines).strip("\n")
    props = dict(org.get("properties") or {})
    props.pop("LAST_REPEAT", None)
    org["properties"] = props
    return org


def _date(value):
    if not value:
        return "none"
    m = re.search(r"\d{4}-\d{2}-\d{2}", str(value))
    return m.group(0) if m else str(value)


def _snapshot_with_ids(text, space_name):
    """Fields per id; a heading typed without an :ID: gets a fresh one (marked new)."""
    from org_workspace._vendor.orgparse import loads
    from ledger.projection_state import snapshot
    from collections import Counter
    ids = [n.get_property("ID") for n in loads(text)[1:] if n.get_property("ID")]
    dups = sorted(i for i, c in Counter(ids).items() if c > 1)
    if dups:
        return None, dups, set()
    minted = set()
    lines = text.splitlines()
    out = []
    i = 0
    heading = re.compile(r"^\*+ ")
    while i < len(lines):
        line = lines[i]
        out.append(line)
        if heading.match(line):
            # the node's own drawer, if any, starts after planning lines
            j = i + 1
            while j < len(lines) and re.match(r"^\s*(SCHEDULED|DEADLINE|CLOSED):", lines[j]):
                out.append(lines[j]); j += 1
            if j < len(lines) and lines[j].strip() == ":PROPERTIES:":
                k = j
                has_id = False
                while k < len(lines) and lines[k].strip() != ":END:":
                    if re.match(r"^\s*:ID:\s*\S", lines[k]):
                        has_id = True
                    k += 1
                if not has_id:
                    new = str(uuid.uuid4())
                    minted.add(new)
                    out.append(lines[j]); out.append(f":ID:       {new}")
                    j += 1
            else:
                new = str(uuid.uuid4())
                minted.add(new)
                out.extend([":PROPERTIES:", f":ID:       {new}", ":END:"])
            i = j
            continue
        i += 1
    fixed = "\n".join(out) + "\n"
    return snapshot(fixed, space_name)["items"], [], minted


def _cmd(*parts):
    return shlex.join(["python3", str(ADAPTER), *map(str, parts)])


def plan(space, text=None):
    """What the hand edit in `space`'s list asks for: (commands, refusals, changed).

    Each command is (argv, display); each refusal is (who, why, command to use).
    The list is compared with what the projector last wrote (the projection
    base) or, with no base, with the ledger's rendering.
    """
    space = Path(space).resolve()
    from ledger_project_org import ORG
    from ledger.projection_state import load_base, snapshot, changed_fields, edit_strict
    target = space / ORG
    text = target.read_text(encoding="utf-8") if text is None else text
    base = load_base(space)
    if base is None:
        base = snapshot(ledger_text(space), space.name)
    base_items = base["items"]
    current, dups, minted = _snapshot_with_ids(text, space.name)
    commands, refusals = [], []
    if current is None:
        refusals.append(("the list", f"duplicate :ID: {', '.join(dups)}",
                         "remove the copy in your saved edit and apply the change with the adapter"))
        return commands, refusals, True
    strict = edit_strict(space)
    f = str(target)
    changed = False
    for tid, fields in current.items():
        old = base_items.get(tid)
        if old is None:
            changed = True
            org = fields.get("org") or {}
            if org.get("properties"):
                refusals.append((fields["title"], "a new heading with properties",
                                 _cmd("add", "--file", f, "--allow-any-file", "--heading", fields["title"],
                                      *sum((["--property", f"{k}={v}"] for k, v in org["properties"].items()), []))))
                continue
            argv = ["add", "--file", f, "--allow-any-file", "--heading", fields["title"],
                    "--state", fields.get("state") or "TODO", "--property", f"ID={tid}"]
            if fields.get("tags"):
                argv += ["--tags", ":" + ":".join(fields["tags"]) + ":"]
            if org.get("priority"):
                argv += ["--priority", org["priority"]]
            if fields.get("scheduled"):
                argv += ["--scheduled", _date(fields["scheduled"])]
            if org.get("body"):
                argv += ["--body", org["body"]]
            if fields.get("parent"):
                argv += ["--parent-id", fields["parent"]]
            commands.append(argv)
            if fields.get("deadline"):
                commands.append(["update", "--file", f, "--id", tid, "--deadline", _date(fields["deadline"])])
            continue
        diff = changed_fields(fields, old, strict=strict)
        if not diff:
            continue
        changed = True
        if "state" in diff and "org" in diff and \
                _without_state_noise(fields.get("org")) == _without_state_noise(old.get("org")):
            diff.pop("org")
        if "tags" not in diff:
            diff.pop("effective_tags", None)
        argv = ["update", "--file", f, "--id", tid]
        if "state" in diff:
            argv += ["--state", diff.pop("state")]
        if "scheduled" in diff:
            argv += ["--scheduled", _date(diff.pop("scheduled"))]
        if "deadline" in diff:
            argv += ["--deadline", _date(diff.pop("deadline"))]
        if not diff:
            commands.append(argv)
            continue
        # Something no recognised command covers: the whole item is refused,
        # with the exact command for every part that has one.
        use = list(argv)
        why = []
        if "title" in diff:
            use += ["--heading", diff.pop("title")]
            why.append("title")
        if "tags" in diff:
            use += ["--tags", ":" + ":".join(diff.pop("tags") or []) + ":"]
            diff.pop("effective_tags", None)
            why.append("tags")
        if "org" in diff:
            new_org, old_org = fields.get("org") or {}, old.get("org") or {}
            for k, v in (new_org.get("properties") or {}).items():
                if (old_org.get("properties") or {}).get(k) != v:
                    use += ["--property", f"{k}={v}"]
            if any(new_org.get(k) != old_org.get(k) for k in ("body", "priority", "created")):
                why.append("body/priority (no adapter command edits these; use the app)")
            else:
                why.append("properties")
            diff.pop("org")
        if diff:
            why.append("/".join(sorted(diff)) + " (no adapter command moves a task in the list; use the app)")
        refusals.append((tid, "changed " + ", ".join(why), _cmd(*use)))
    for tid in base_items.keys() - current.keys():
        changed = True
        refusals.append((tid, "heading deleted (a task leaves the list by closing it)",
                         _cmd("update", "--file", f, "--id", tid, "--state", "CANCELLED")))
    return commands, refusals, changed


def _save_edit(space, text) -> Path:
    """Keep the edited text verbatim. Named by content, so a re-check reuses it."""
    import hashlib
    from file_utils import atomic_write_text
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
    folder = Path(space) / REFUSED_DIR
    for existing in sorted(folder.glob(f"*-{digest}-next_actions.org")) if folder.is_dir() else []:
        if existing.read_text(encoding="utf-8") == text:
            return existing
    stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    path = folder / f"{stamp}-{digest}-next_actions.org"
    atomic_write_text(path, text)
    return path


def restore(space) -> str:
    """Write the ledger's list over the file. Only after the file was saved."""
    from org_transaction import serialized, watch_file, write_org_text
    from ledger_project_org import ORG, rendered, HEADER_COPY
    from ledger.projection_state import STATE, base_document
    space = Path(space).resolve()

    @serialized
    def run():
        target = space / ORG
        watch_file(target)
        watch_file(space / STATE)
        watch_file(space / HEADER_COPY)
        text = rendered(space, as_of=time.time(), remember=True)
        with regenerating():
            write_org_text(target, text)
        write_org_text(space / STATE, base_document(text))
        return target

    target = run()
    if enabled(space):
        lock(target)
    return f"restored {ORG} from the ledger"


def _run_adapter(argv):
    import org_workspace_adapter as adapter
    args = adapter.build_parser().parse_args(argv)
    return adapter.COMMAND_MAP[args.command](args)


def hook(space, *, apply=False, quiet=False, out=print) -> int:
    space = Path(space).resolve()
    if not enabled(space):
        if not quiet:
            out(f"{space.name}: read-only lists are off; nothing to check")
        return 0
    from ledger_project_org import ORG
    target = space / ORG
    if not target.exists():
        return 0
    text = target.read_text(encoding="utf-8")
    try:
        commands, refusals, changed = plan(space, text)
    except Exception as exc:  # noqa: BLE001 - an unreadable edit is refused, never dropped
        commands, refusals, changed = [], [("the list", f"unreadable ({type(exc).__name__}: {exc})",
                                            "apply the change with org_workspace_adapter.py")], True
    if not changed:
        if not quiet:
            out(f"{space.name}: no hand edit in {ORG}")
        return 0
    saved = _save_edit(space, text) if (refusals or apply) else None
    for argv in commands:
        out(("APPLY " if apply else "WOULD RUN ") + _cmd(*argv))
    for who, why, use in refusals:
        out(f"REFUSED {who}: {why}. Your edit is saved to {saved} ; to make this change run: {use}")
    if not apply:
        if commands and not refusals:
            out(f"{len(commands)} command(s) wait; run: python3 {LIB / 'org_readonly.py'} hook --space {space} --apply")
        return 2 if refusals else 1
    failed = 0
    for argv in commands:
        try:
            result = _run_adapter(argv)
        except Exception as exc:  # noqa: BLE001
            result = {"error": f"{type(exc).__name__}: {exc}"}
        if isinstance(result, dict) and result.get("error"):
            failed += 1
            out(f"FAILED {_cmd(*argv)}: {result['error']} (edit saved to {saved})")
    out(restore(space) + (f"; your edit is saved to {saved}" if saved else ""))
    return 2 if (refusals or failed) else 0


# -- the trial checker -------------------------------------------------------

def _record_trial_start(space):
    from file_utils import atomic_write_text
    groups = _title_groups(space)
    atomic_write_text(Path(space) / TRIAL, json.dumps(
        {"version": 1, "started": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
         "same_title_ids": sorted(i for ids in groups.values() for i in ids)}) + "\n")


def _title_groups(space):
    from ledger.hub import authoritative_state
    from ledger.projector import LIVE_STATUSES
    titles = {}
    for item in authoritative_state(Path(space)).items.values():
        if item.status in LIVE_STATUSES:
            titles.setdefault((item.payload or {}).get("title"), []).append(item.id)
    return {t: ids for t, ids in titles.items() if t and len(ids) > 1}


def trial_check(space, out=print) -> int:
    """Tasks (id, state) in the list against the ledger. Last line for a job contract."""
    space = Path(space).resolve()
    from collections import Counter
    from ledger_project_org import ORG
    from ledger.projection_state import snapshot
    from org_workspace._vendor.orgparse import loads
    expected = {tid: f.get("state") for tid, f in snapshot(ledger_text(space), space.name)["items"].items()}
    target = space / ORG
    text = target.read_text(encoding="utf-8") if target.exists() else ""
    from org_workspace._vendor.orgparse.node import OrgEnv
    # The canonical states (DIP-0009 v2.0), in case a list lacks its #+SEQ_TODO line.
    env = OrgEnv(todos=["TODO", "NEXT", "WAITING", "REVIEW"], dones=["DONE", "DEFERRED", "CANCELLED"],
                 filename="<string>")
    nodes = list(loads(text, env=env)[1:])  # a slice of the root is a one-pass iterator
    ids = [n.get_property("ID") for n in nodes]
    counts = Counter(i for i in ids if i)
    # orgparse, not OrgWorkspace: a doubled :ID: must be counted, not refused.
    states = {n.get_property("ID"): n.todo for n in nodes if n.get_property("ID")}
    lost = sorted(expected.keys() - counts.keys())
    extra = sorted(counts.keys() - expected.keys())
    doubled = sorted(i for i, c in counts.items() if c > 1)
    unidentified = sum(1 for i in ids if not i)
    differ = sorted(i for i in expected.keys() & counts.keys() if expected[i] != states.get(i))
    try:
        baseline = set(json.loads((space / TRIAL).read_text())["same_title_ids"])
    except (OSError, ValueError, KeyError):
        baseline = None
    twins = []
    if baseline is not None:
        for title, group in _title_groups(space).items():
            if any(i not in baseline for i in group):
                twins.append(group)
    for tid in lost:
        out(f"lost: {tid} is live in the ledger and missing from {ORG}")
    for tid in doubled:
        out(f"doubled: {tid} appears {counts[tid]} times in {ORG}")
    for group in twins:
        out(f"doubled: ledger items {', '.join(sorted(group))} share one title (new since the trial started)")
    for tid in extra:
        out(f"extra: {tid} is in {ORG} but not in the ledger's view")
    for tid in differ:
        out(f"state differs: {tid} is {states.get(tid)} in {ORG}, {expected[tid]} in the ledger")
    if unidentified:
        out(f"unidentified: {unidentified} heading(s) without an :ID: (a hand edit; run the hook)")
    n_doubled = len(doubled) + len(twins)
    bad = lost or n_doubled or extra or differ or unidentified
    word = "FAIL" if bad else "OK"
    tail = "" if not bad else f", {len(extra)} extra, {len(differ)} state-differ, {unidentified} unidentified"
    out(f"{word} {space.name} {len(expected)} task(s), {len(lost)} lost, {n_doubled} doubled{tail}")
    return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("command", choices=("on", "off", "status", "hook", "trial-check"))
    ap.add_argument("--space", type=Path, required=True)
    ap.add_argument("--apply", action="store_true", help="hook: run the commands, then restore the view")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    space = a.space.resolve()
    if not (space / ".datacore").is_dir():
        print(f"not a space: {space}", file=sys.stderr)
        return 2
    if a.command == "on":
        code, line = switch_on(space)
        print(line)
        return code
    if a.command == "off":
        code, line = switch_off(space)
        print(line)
        return code
    if a.command == "status":
        print(f"{space.name}: read-only lists {'ON' if enabled(space) else 'off'}"
              + (f"; authored lists: {', '.join(authored_lists(space))}" if authored_lists(space) else ""))
        return 0
    if a.command == "hook":
        return hook(space, apply=a.apply, quiet=a.quiet)
    return trial_check(space)


